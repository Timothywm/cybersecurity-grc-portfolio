#!/usr/bin/env python3
"""Compare investigation findings with the generator's ground truth -> docs/06-validation-vs-ground-truth.md
Run only AFTER the investigation is written up.
  python3 tools/validate_findings.py --pcap lab/raw/incident-01.pcap --gt lab/ground_truth.csv --findings tools/findings.csv
"""
import argparse, csv, subprocess

def cap_start(pcap):
    out = subprocess.run(["tshark", "-r", pcap, "-c", "1", "-T", "fields", "-e", "frame.time_epoch"], capture_output=True, text=True, check=True)
    return float(out.stdout.split()[0])

def sset(s): return {x.strip() for x in s.split(",") if x.strip()}
def overlap(a0, a1, b0, b1, pad): return a0 - pad <= b1 and b0 - pad <= a1

def iou(a0, a1, b0, b1, pad=5.0):
    inter = max(0.0, min(a1, b1) - max(a0, b0))
    union = max(a1, b1) - min(a0, b0)
    if union > 0 and inter > 0:
        return inter / union
    if overlap(a0, a1, b0, b1, pad):
        gap = max(0.0, max(a0, b0) - min(a1, b1))
        return 1e-3 / (1.0 + gap)
    return 0.0

def tech_bonus(gt_tech, f_tech):
    gt_set = {t.split('.')[0] for t in gt_tech.replace('/', ',').split(',') if t.strip()}
    f_set = {t.split('.')[0] for t in f_tech.replace('/', ',').split(',') if t.strip()}
    if gt_tech in f_tech or f_tech in gt_tech:
        return 0.5
    if gt_set & f_set:
        return 0.25
    return 0.0

def validate(gt_rows, findings, t0, pad=5.0):
    res = []
    for g in gt_rows:
        g0, g1 = float(g["start_epoch"]) - t0, float(g["end_epoch"]) - t0
        benign = g["attack_technique"] == "legitimate"
        best = None
        best_score = 0.0
        for f in findings:
            if not (sset(g["src"]) & sset(f["src"]) and sset(g["dst"]) & sset(f["dst"])): continue
            if (f["verdict"] == "benign") != benign: continue
            f0, f1 = float(f["start_s"]), float(f["end_s"])
            if not overlap(g0, g1, f0, f1, pad): continue
            score = iou(g0, g1, f0, f1, pad) + (0.0 if benign else tech_bonus(g["attack_technique"], f["technique"]))
            if score > best_score:
                best_score = score
                best = f
        res.append((g, g0, g1, benign, best))
    return res

def main():
    ap = argparse.ArgumentParser(); ap.add_argument("--pcap"); ap.add_argument("--gt", required=True); ap.add_argument("--findings", required=True)
    ap.add_argument("--out", default="docs/06-validation-vs-ground-truth.md"); ap.add_argument("--t0", type=float, help="capture start epoch (skip tshark)")
    a = ap.parse_args()
    t0 = a.t0 if a.t0 is not None else cap_start(a.pcap)
    gt = list(csv.DictReader(open(a.gt))); fi = list(csv.DictReader(open(a.findings)))
    res = validate(gt, fi, t0)
    mal = [r for r in res if not r[3]]; ben = [r for r in res if r[3]]
    hit = [r for r in mal if r[4]]; okb = [r for r in ben if r[4]]
    used = {r[4]["id"] for r in res if r[4]}
    extra = [f for f in fi if f["id"] not in used]
    L = ["# 06 - Validation against ground truth", "",
         "Generated by `tools/validate_findings.py` after the investigation was written. Ground truth comes from the traffic generator (`lab/ground_truth.csv`, not published); findings come from `tools/findings.csv`.", "",
         "| Metric | Result |", "|---|---|",
         f"| Attack stages identified | **{len(hit)} / {len(mal)}** |",
         f"| Benign activity correctly classified | **{len(okb)} / {len(ben)}** |",
         f"| Findings with no ground-truth counterpart (false positives) | **{len(extra)}** |", "",
         "## Stage by stage", "", "| GT stage | ATT&CK (GT) | GT window (s) | Finding | Finding window (s) | Start offset (s) |", "|---|---|---|---|---|---|"]
    for g, g0, g1, benign, f in res:
        if f: L.append(f"| {g['stage']} | {g['attack_technique']} | {g0:.0f}-{g1:.0f} | {f['id']} ({f['technique']}) | {float(f['start_s']):.0f}-{float(f['end_s']):.0f} | {float(f['start_s']) - g0:+.1f} |")
        else: L.append(f"| {g['stage']} | {g['attack_technique']} | {g0:.0f}-{g1:.0f} | **not found** | - | - |")
    if extra: L += ["", "## Findings without a ground-truth match", ""] + [f"- {f['id']}: {f['summary']}" for f in extra]
    L += ["", "Offsets compare the first observed packet of a finding with the generator's stage start. Positive values mean the stage was first seen later than its nominal start (probe phases and retries inside a stage cause this)."]
    open(a.out, "w").write("\n".join(L) + "\n")
    print(f"stages {len(hit)}/{len(mal)} | benign {len(okb)}/{len(ben)} | extra {len(extra)} -> {a.out}")

if __name__ == "__main__":
    main()